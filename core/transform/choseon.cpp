choseonLatin::choseonLatin(std::string input)
    : transforml(input) {
    this->type = transformType::eonmonLatin;
}

void choseonLatin::transform() {
    std::string out;
    out.reserve(this->input.size() * 2);
    const auto& table = syllableTable();
    for (size_t i = 0; i < this->input.size(); ) {
        unsigned char c = static_cast<unsigned char>(this->input[i]);
        if (c >= 0xEA && c <= 0xED && i + 2 < this->input.size()) {
            std::string key = this->input.substr(i, 3);
            auto it = table.find(key);
            if (it != table.end()) {
                out += it->second;
                i += 3;
                continue;
            }
        }
        out.push_back(this->input[i]);
        ++i;
    }
    this->output = out;
}

void choseonLatin::outputl() {
    this->transform();
    std::cout << this->output << std::endl;
}

